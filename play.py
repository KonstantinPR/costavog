import re


def pad_last_number_in_filename(filename):
    # Match the last hyphen and the number after it before the extension

    # Remove all whitespace characters
    filename = re.sub(r'\s+', '', filename)

    pattern = r'(.*-)(\d+)(\.\w+)$'
    match = re.match(pattern, filename)
    if match:
        prefix, number, suffix = match.groups()
        # Pad the number to 3 digits
        padded_number = number.zfill(3)
        return f"{prefix}{padded_number}{suffix}"
    else:
        # If pattern doesn't match, return filename unchanged
        return filename


